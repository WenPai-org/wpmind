<?php
/**
 * PHPCS baseline gate.
 *
 * PHPCS has no native baseline. This script runs the project's own PHPCS
 * (vendor/squizlabs/php_codesniffer) with phpcs.xml.dist plus
 * tests/phpcs-compat.xml, groups every message by "relative path + sniff
 * source", and compares the counts with tests/baseline/phpcs-baseline.json.
 *
 * Usage:
 *   php tests/phpcs-baseline.php             Compare with the baseline (fails on any increase).
 *   php tests/phpcs-baseline.php --generate  Rewrite the baseline from the current tree.
 *
 * @package WPMind
 */

declare(strict_types=1);

$root          = dirname( __DIR__ );
$baseline_file = $root . '/tests/baseline/phpcs-baseline.json';
$phpcs_bin     = $root . '/vendor/squizlabs/php_codesniffer/bin/phpcs';
$standards     = [ 'phpcs.xml.dist', 'tests/phpcs-compat.xml' ];
$generate      = in_array( '--generate', array_slice( $argv, 1 ), true );

if ( ! is_file( $phpcs_bin ) ) {
	fwrite( STDERR, 'PHPCS not found at vendor/squizlabs/php_codesniffer/bin/phpcs. Run "composer install" first.' . PHP_EOL );
	exit( 2 );
}

$command = array_merge(
	[ PHP_BINARY, $phpcs_bin ],
	[
		'--standard=' . implode( ',', $standards ),
		'--report=json',
		'--basepath=' . $root,
		'--no-colors',
		'-q',
	]
);

$descriptors = [
	1 => [ 'pipe', 'w' ],
	2 => [ 'pipe', 'w' ],
];
$process     = proc_open( $command, $descriptors, $pipes, $root );
if ( ! is_resource( $process ) ) {
	fwrite( STDERR, 'Unable to start PHPCS.' . PHP_EOL );
	exit( 2 );
}
$stdout = (string) stream_get_contents( $pipes[1] );
$stderr = (string) stream_get_contents( $pipes[2] );
fclose( $pipes[1] );
fclose( $pipes[2] );
$exit_code = proc_close( $process );

$report = json_decode( $stdout, true );
if ( ! is_array( $report ) || ! isset( $report['files'], $report['totals'] ) ) {
	fwrite( STDERR, "PHPCS did not produce a JSON report (exit code {$exit_code})." . PHP_EOL );
	fwrite( STDERR, trim( $stdout . PHP_EOL . $stderr ) . PHP_EOL );
	exit( 2 );
}

/**
 * Normalise a report path to a forward-slash path relative to the project root.
 *
 * @param string $path Path from the PHPCS report.
 * @return string
 */
function wpmind_phpcs_relative_path( string $path ): string {
	$path = str_replace( '\\', '/', $path );
	return ltrim( preg_replace( '#^\./#', '', $path ) ?? $path, '/' );
}

$counts    = [];
$locations = [];
foreach ( $report['files'] as $path => $file ) {
	$relative = wpmind_phpcs_relative_path( (string) $path );
	foreach ( $file['messages'] as $message ) {
		$source                             = (string) $message['source'];
		$counts[ $relative ][ $source ]     = ( $counts[ $relative ][ $source ] ?? 0 ) + 1;
		$locations[ $relative ][ $source ][] = sprintf(
			'%s:%d:%d %s %s',
			$relative,
			(int) $message['line'],
			(int) $message['column'],
			strtolower( (string) $message['type'] ),
			(string) $message['message']
		);
	}
}
ksort( $counts );
foreach ( $counts as &$sources ) {
	ksort( $sources );
}
unset( $sources );

$errors   = (int) $report['totals']['errors'];
$warnings = (int) $report['totals']['warnings'];

if ( $generate ) {
	$dir = dirname( $baseline_file );
	if ( ! is_dir( $dir ) && ! mkdir( $dir, 0777, true ) && ! is_dir( $dir ) ) {
		fwrite( STDERR, "Unable to create {$dir}." . PHP_EOL );
		exit( 2 );
	}
	$data = [
		'_comment'  => 'Generated by "composer cs:baseline". Counts of PHPCS messages per file and sniff source; do not edit by hand.',
		'standards' => $standards,
		'totals'    => [
			'errors'   => $errors,
			'warnings' => $warnings,
		],
		'files'     => $counts,
	];
	file_put_contents( $baseline_file, json_encode( $data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE ) . PHP_EOL );
	echo "PHPCS baseline written to tests/baseline/phpcs-baseline.json ({$errors} errors, {$warnings} warnings)." . PHP_EOL;
	exit( 0 );
}

if ( ! is_file( $baseline_file ) ) {
	fwrite( STDERR, 'Missing tests/baseline/phpcs-baseline.json. Run "composer cs:baseline" to create it.' . PHP_EOL );
	exit( 2 );
}

$baseline = json_decode( (string) file_get_contents( $baseline_file ), true );
if ( ! is_array( $baseline ) || ! isset( $baseline['files'] ) || ! is_array( $baseline['files'] ) ) {
	fwrite( STDERR, 'tests/baseline/phpcs-baseline.json is not valid.' . PHP_EOL );
	exit( 2 );
}

$regressions = [];
$improved    = 0;
foreach ( $counts as $relative => $sources ) {
	foreach ( $sources as $source => $count ) {
		$allowed = (int) ( $baseline['files'][ $relative ][ $source ] ?? 0 );
		if ( $count > $allowed ) {
			$regressions[] = [ $relative, $source, $allowed, $count ];
		}
	}
}
foreach ( $baseline['files'] as $relative => $sources ) {
	foreach ( $sources as $source => $allowed ) {
		$current = (int) ( $counts[ $relative ][ $source ] ?? 0 );
		if ( $current < (int) $allowed ) {
			$improved += (int) $allowed - $current;
		}
	}
}

if ( $regressions ) {
	fwrite( STDERR, 'PHPCS: new violations above the baseline:' . PHP_EOL );
	foreach ( $regressions as [ $relative, $source, $allowed, $count ] ) {
		fwrite( STDERR, sprintf( '  %s  %s  baseline %d, now %d', $relative, $source, $allowed, $count ) . PHP_EOL );
		foreach ( $locations[ $relative ][ $source ] as $location ) {
			fwrite( STDERR, '    ' . $location . PHP_EOL );
		}
	}
	fwrite( STDERR, 'Fix the new violations (all locations of each affected group are listed above).' . PHP_EOL );
	exit( 1 );
}

echo "PHPCS OK: no violations above the baseline ({$errors} errors, {$warnings} warnings)." . PHP_EOL;
if ( $improved > 0 ) {
	echo "PHPCS: {$improved} baseline violation(s) are gone; run \"composer cs:baseline\" to tighten the baseline." . PHP_EOL;
}
exit( 0 );
